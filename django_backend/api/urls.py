    path("api/auth/register", register, name="auth-register"),
    path("api/auth/login", login, name="auth-login"),
    path("api/auth/me", me, name="auth-me"),
    path("api/auth/workspaces", workspaces, name="auth-workspaces"),
    path("api/auth/workspaces/create", create_workspace, name="workspace-create"),
    path("api/auth/workspaces/<uuid:workspace_id>", update_workspace, name="workspace-update"),
    path("api/auth/workspaces/<uuid:workspace_id>/invitations", create_invitation, name="invitation-create"),
    path("api/auth/workspaces/<uuid:workspace_id>/invitations/list", list_invitations, name="invitation-list"),
    path("api/auth/workspaces/<uuid:workspace_id>/invitations/<uuid:invitation_id>", revoke_invitation, name="invitation-revoke"),
    path("api/auth/workspaces/<uuid:workspace_id>/members", list_members, name="member-list"),
    path("api/auth/workspaces/<uuid:workspace_id>/members/<uuid:member_id>", update_member, name="member-update"),
    path("api/auth/workspaces/<uuid:workspace_id>/members/<uuid:member_id>/remove", remove_member, name="member-remove"),
    path("api/auth/invitations/accept", accept_invitation, name="invitation-accept"),
    path("api/repos", list_repositories, name="repository-list"),
    path("api/repos/connect", connect_repository, name="repository-connect"),
    path("api/repos/<uuid:repo_id>/reindex", reindex_repository, name="repository-reindex"),
