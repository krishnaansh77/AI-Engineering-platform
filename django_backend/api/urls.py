    path("api/repos/<uuid:repo_id>/graph/files", repository_graph, name="repository-graph"),
    path("api/repos/<uuid:repo_id>/architecture", repository_architecture, name="repository-architecture"),
    path("api/repos/<uuid:repo_id>/test-intelligence", repository_tests, name="repository-tests"),
    path("api/repos/<uuid:repo_id>/tour", repository_tour, name="repository-tour"),
    path("api/repos/<uuid:repo_id>/technical-debt", repository_debt, name="repository-debt"),
